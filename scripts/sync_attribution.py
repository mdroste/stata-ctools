"""Copy config/attribution.json into docs/ATTRIBUTION.md, the Acknowledgments of
each help file, help ctools, and the ado-file headers; --check rejects stale copies.

config/attribution.json records the original command behind each ctools command
and the version ctools is pinned to.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "{* ctools-attribution:begin (generated by scripts/sync_attribution.py; edit config/attribution.json)}{...}"
END = "{* ctools-attribution:end}{...}"
CREDIT_BEGIN = "{* ctools-credit:begin (generated by scripts/sync_attribution.py; edit config/attribution.json)}{...}"
CREDIT_END = "{* ctools-credit:end}{...}"
ADO = "*! original: "
MARKUP = re.compile(r"\[([^\]]+)\]\(([^)]+)\)|`([^`]+)`|\*\*([^*]+)\*\*|\*([^*]+)\*")
COUNT = {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five"}


# ---------------------------------------------------------------- markup

def smcl(text):
    """`command`, *italic*, **bold** and [text](url) as SMCL."""
    def directive(match):
        label, url, command, bold, italic = match.groups()
        if label is not None:
            if url.startswith("help:"):
                return "{help %s:%s}" % (url[5:], smcl(label))
            return '{browse "%s":%s}' % (url, smcl(label))
        if command is not None:
            return "{cmd:%s}" % command
        if bold is not None:
            return "{bf:%s}" % smcl(bold)
        return "{it:%s}" % italic
    return MARKUP.sub(directive, text)


def markdown(text):
    """The markup is Markdown, except links to Stata help files."""
    return re.sub(r"\[([^\]]+)\]\(help:[^)]+\)", lambda m: "`" + m.group(1).strip("`") + "`", text)


def plain(text):
    return MARKUP.sub(lambda m: next(g for g in (m.group(1), m.group(3), m.group(4), m.group(5)) if g is not None), text)


def fill(text, width=78):
    """Wrap SMCL without breaking a directive across lines."""
    words, depth, word = [], 0, ""
    for char in text:
        depth += (char == "{") - (char == "}")
        if char == " " and depth == 0:
            if word:
                words.append(word)
            word = ""
        else:
            word += char
    if word:
        words.append(word)
    lines, line = [], ""
    for word in words:
        if line and len(line) + 1 + len(word) > width:
            lines.append(line)
            line = word
        else:
            line = f"{line} {word}" if line else word
    return lines + [line] if line else lines


def listing(items, separator=","):
    items = list(items)
    if len(items) < 3:
        return " and ".join(items)
    return f"{separator} ".join(items[:-1]) + f"{separator} and " + items[-1]


# ---------------------------------------------------------------- sentences

def community(c):
    return [o for o in c["originals"] if o["kind"] == "community"]


def official(c):
    return [o for o in c["originals"] if o["kind"] != "community"]


def family(o):
    """A row that stands for several official ado-files at once."""
    return o["kind"] == "official" and not o.get("file")


def written_by(o):
    """The credit Stata's manual gives for an official command, if any."""
    return o["authors"].split("; ", 1)[1] if "; " in o["authors"] else ""


def brief(o):
    """One original in one phrase, for help ctools and the ado header."""
    if o["kind"] == "community":
        return f"`{o['name']}` {o.get('short') or o['version'] + ' (' + o['date'] + ')'} by {o['authors']}"
    if family(o):
        return f"Stata's other `{o['which']}` commands"
    credit = written_by(o)
    credit = f", {credit}" if credit else ""
    if o["kind"] == "builtin":
        return f"Stata's `{o['name']}` (built in){credit}"
    return f"Stata's `{o['name']}` (`{o['file']}` {o['version']}, {o['date']}){credit}"


def rows(d, o, checksum):
    stata = f"{d['stata']['release']} (revision {d['stata']['revision']})"
    if o["kind"] == "community":
        header = f"`{o['header']}`" + (f" ({o['header_note']})" if o.get("header_note") else "")
        source = f"{o['channel']} (`{o['install']}`), distributed {o['distributed']}."
        if o.get("note"):
            source += " " + o["note"]
        out = [
            ("Command", f"`{o['name']}`"),
            ("Authors", o["authors"]),
            ("Version", o["version"]),
            ("Date", o["date"]),
            ("Header line", header),
            ("Source", source),
            ("Latest version?", o.get("status") or f"Yes, as of {d['recorded']}."),
        ]
    elif family(o):
        out = [
            ("Commands", f"Other official `{o['which']}` commands"),
            ("Authors", o["authors"]),
            ("Versions", o["version"]),
            ("Shipped with", stata),
        ]
    elif o["kind"] == "builtin":
        out = [
            ("Command", f"`{o['name']}` (official Stata)"),
            ("Authors", o["authors"]),
            ("Version", "Built in (no version line)"),
            ("Shipped with", stata),
        ]
    else:
        out = [
            ("Command", f"`{o['name']}` (official Stata)"),
            ("Authors", o["authors"]),
            ("Version", f"`{o['file']}` {o['version']}"),
            ("Date", o["date"]),
            ("Header line", f"`{o['header']}`"),
            ("Shipped with", stata),
        ]
    if checksum and o.get("sha256"):
        out.append(("SHA-256", f"`{o['sha256']}` (`{o['file']}`)"))
    return out


def lead(c):
    if len(c["originals"]) == 1:
        return f"`{c['command']}` is pinned to this version of `{c['originals'][0]['name']}`:"
    return f"`{c['command']}` is pinned to these versions:"


def tracking(c):
    """When the ctools command changes, and how to see the installed original."""
    cmd, comm, off = c["command"], community(c), official(c)
    everything = "[help ctools](help:ctools##acknowledgments) lists the pinned versions of all ctools commands."
    if not comm:
        one = len(off) == 1
        text = f"`{cmd}` follows {'`' + off[0]['name'] + '`' if one else 'these commands'} as "
        text += f"{'it behaves' if one else 'they behave'} in this Stata release."
        if one and off[0].get("file"):
            text += f" `which {off[0].get('which', off[0]['name'])}` shows the version of `{off[0]['file']}` in your Stata."
        return f"{text} {everything}"
    if len(c["originals"]) == 1:
        o = comm[0]
        return (
            f"`{cmd}` changes only when ctools is updated to a newer version of `{o['name']}` and tested against it. "
            f"`which {o.get('which', o['name'])}` shows the version installed on your machine. {everything}"
        )
    return (
        f"`{cmd}` changes only when ctools is updated to newer versions of these commands and tested against them. "
        f"`which` shows the version of each command installed on your machine. {everything}"
    )


def feedback(d, c):
    cmd, comm, off = c["command"], community(c), official(c)
    site = d["issues"].split("//", 1)[1]
    authors = "the authors of " + listing(f"`{o['name']}`" for o in comm) if comm else ""
    if comm and off:
        who = f"StataCorp and {authors} do not maintain `{cmd}`."
    elif off:
        who = f"StataCorp does not support `{cmd}`."
    else:
        who = f"{authors[0].upper() + authors[1:]} do not maintain `{cmd}`."
    other = f"`{c['originals'][0]['name']}`" if len(c["originals"]) == 1 else "the original commands"
    return (
        f"Please report bugs and questions about `{cmd}` at [{site}]({d['issues']}). {who} "
        f"Undocumented differences between `{cmd}` and {other} are bugs in `{cmd}`."
    )


def credit(c):
    """The paragraph that opens the Description of a help file."""
    cmd = c["command"]
    what = listing((brief(o) for o in c["originals"]), separator=";")
    return f"`{cmd}` reimplements {what}. See [Acknowledgments](help:{cmd}##acknowledgments) for details."


def supporting(d, c):
    names = c.get("supporting", [])
    if not names:
        return ""
    table = {s["name"]: s for s in d["supporting"]}
    items = "; ".join(f"`{n}` {table[n]['version']} ({table[n]['date']}) by {table[n]['authors']}" for n in names)
    return f"Tests also used these packages: {items}."


def behind(d, link):
    """ctools commands pinned to a version that is no longer the latest."""
    return [
        f"[`{c['command']}`]({link.format(command=c['command'])}) follows `{o['name']}` {o['version']} ({o['date']}); "
        f"{o['newer']}."
        for c in d["commands"] for o in community(c) if o.get("newer")
    ]


def behind_lead(items):
    if len(items) == 1:
        return "One command is pinned to a version that is no longer the latest:"
    return f"{COUNT.get(len(items), len(items))} commands are pinned to versions that are no longer the latest:"


def citing(c):
    if not c.get("references"):
        return ""
    if community(c):
        return f"If you use `{c['command']}` in published work, please cite the original command:"
    return "The original command is described in:"


# ---------------------------------------------------------------- help files

def table_smcl(rows_):
    out = ["{p2colset 9 27 29 2}{...}"]
    for label, text in rows_:
        out.extend(fill("{p2col:%s}%s{p_end}" % (label, smcl(text))))
    out.append("{p2colreset}{...}")
    return out


def paragraph(text):
    return ["{pstd}"] + fill(smcl(text)) + [""]


def help_block(d, c):
    out = [BEGIN, "{marker acknowledgments}{...}", "{title:Acknowledgments}", ""]
    out += paragraph(c["intro"])
    out += paragraph(lead(c))
    for o in c["originals"]:
        out += table_smcl(rows(d, o, checksum=False)) + [""]
    for text in c.get("later", []):
        out += paragraph(text)
    out += paragraph(tracking(c))
    out += paragraph(feedback(d, c))
    for text in c.get("credits", []):
        out += paragraph(text)
    if supporting(d, c):
        out += paragraph(supporting(d, c))
    if citing(c):
        out += paragraph(citing(c))
        for ref in c["references"]:
            out += fill("{phang2}" + smcl(ref) + "{p_end}") + [""]
    while out[-1] == "":
        out.pop()
    return out + [END]


def credit_block(c):
    return [CREDIT_BEGIN, "{pstd}"] + fill(smcl(credit(c))) + [CREDIT_END]


def ctools_block(d):
    out = [BEGIN, "{marker acknowledgments}{...}", "{title:Acknowledgments}", ""]
    out += paragraph(
        "ctools reimplements existing Stata commands in C. Each ctools command takes its syntax, options, output, "
        "and stored results from the command it replaces, and is pinned to one version of that command. The "
        "Acknowledgments section of each command's help file has details and references."
    )
    out += ["{pstd}", "{ul:Community-contributed commands}", "", "{p2colset 5 20 22 2}{...}"]
    for c in d["commands"]:
        if community(c):
            text = "; ".join(brief(o) for o in c["originals"])
            out += fill("{p2col:{help %s##acknowledgments:%s}}%s{p_end}" % (c["command"], c["command"], smcl(text)))
    out += ["", "{pstd}"]
    out += fill(f"{{ul:Official Stata commands}} ({d['stata']['release']}, revision {d['stata']['revision']})")
    out += [""]
    for c in d["commands"]:
        if not community(c):
            text = "; ".join(brief(o) for o in c["originals"])
            out += fill("{p2col:{help %s##acknowledgments:%s}}%s{p_end}" % (c["command"], c["command"], smcl(text)))
    out += ["", "{pstd}", "{ul:Supporting packages}", ""]
    for s in d["supporting"]:
        text = f"{s['version']} ({s['date']}) by {s['authors']}. {s['role']}."
        out += fill("{p2col:{cmd:%s}}%s{p_end}" % (s["name"], smcl(text)))
    out += ["{p2colreset}{...}", ""]
    stale = behind(d, "help:{command}##acknowledgments")
    recorded = f"Versions were recorded on {d['recorded']}."
    out += paragraph(recorded + (" " + behind_lead(stale) + " " + " ".join(stale) if stale else ""))
    site = d["issues"].split("//", 1)[1]
    out += paragraph(
        f"Please report bugs and questions about ctools commands at [{site}]({d['issues']}). The authors of the "
        "original commands do not maintain ctools. If you use a ctools command in published work, please cite the "
        f"original command. [docs/ATTRIBUTION.md]({d['document']}) has file checksums and all references."
    )
    out += ["{pstd}", "{ul:Other acknowledgments}", ""]
    for text in d["algorithms"]:
        lines = fill("- " + smcl(text) + "{p_end}")
        out += ["{p 8 10 2}" + lines[0]] + lines[1:]
    return out + [END]


def place_help(text, block, name):
    """Put the generated section in a help file: over its previous copy, over a
    hand-written Acknowledgments section, or before Also see."""
    lines = text.split("\n")
    trailing = lines[-1] == ""
    if trailing:
        lines.pop()
    begins = [i for i, line in enumerate(lines) if line.startswith("{* ctools-attribution:begin")]
    ends = [i for i, line in enumerate(lines) if line.startswith("{* ctools-attribution:end")]
    if begins or ends:
        if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
            raise SystemExit(f"build/{name}.sthlp: damaged ctools-attribution markers")
        lines[begins[0]:ends[0] + 1] = block
    else:
        also = next((i for i, line in enumerate(lines) if line.startswith("{title:Also see}")), len(lines))
        if also < len(lines) and also and lines[also - 1].startswith("{marker "):
            also -= 1
        old = next((i for i, line in enumerate(lines) if line.startswith("{title:Acknowledgments}")), None)
        if old is not None and old < also:
            if old and lines[old - 1].startswith("{marker "):
                old -= 1
            start = old
        else:
            start = also
        while start and lines[start - 1] == "":
            start -= 1
        tail = lines[also:]
        lines[start:] = ["", ""] + block + (["", ""] + tail if tail else [])
    jump = '{viewerjumpto "Acknowledgments" "%s##acknowledgments"}{...}' % name
    if jump not in lines:
        jumps = [i for i, line in enumerate(lines) if line.startswith("{viewerjumpto ")]
        if jumps:
            lines.insert(jumps[-1] + 1, jump)
    return "\n".join(lines) + ("\n" if trailing else "")


def place_credit(text, block, name):
    """Open the Description section with the credit paragraph."""
    lines = text.split("\n")
    begins = [i for i, line in enumerate(lines) if line.startswith("{* ctools-credit:begin")]
    ends = [i for i, line in enumerate(lines) if line.startswith("{* ctools-credit:end")]
    if begins or ends:
        if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
            raise SystemExit(f"build/{name}.sthlp: damaged ctools-credit markers")
        lines[begins[0]:ends[0] + 1] = block
        return "\n".join(lines)
    titles = [i for i, line in enumerate(lines) if line.startswith("{title:Description}")]
    if len(titles) != 1:
        raise SystemExit(f"build/{name}.sthlp: expected one Description section")
    at = titles[0] + 1
    while at < len(lines) and lines[at] == "":
        at += 1
    lines[titles[0] + 1:at] = [""] + block + [""]
    return "\n".join(lines)


# ---------------------------------------------------------------- ado headers

def ado_lines(c):
    out = [ADO + plain(brief(o)) for o in c["originals"] if not family(o)]
    return out + [f"{ADO}see help {c['command']} for details"]


def place_ado(text, new):
    lines = [line for line in text.split("\n") if not line.startswith(ADO)]
    at = 0
    while at < len(lines) and lines[at].startswith("*!"):
        at += 1
    return "\n".join(lines[:at] + new + lines[at:])


# ---------------------------------------------------------------- docs/ATTRIBUTION.md

def table_md(header, body):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join(" --- " for _ in header) + "|"]
    out += ["| " + " | ".join(row) + " |" for row in body]
    return out


def document(d):
    stata = d["stata"]
    out = [
        "# Attribution",
        "",
        "<!-- Generated by scripts/sync_attribution.py from config/attribution.json. Edit that file, not this one. -->",
        "",
        "ctools reimplements existing Stata commands in C. Each ctools command takes its syntax, options, output, "
        "and stored results from the command it replaces, and credit for those designs belongs to the original "
        "authors. This page lists each original command, its authors, and the version that the ctools command is "
        "pinned to. The same information appears in each command's help file and ado-file header "
        "(`which cdistinct`).",
        "",
        "## Pinned versions",
        "",
        "Each ctools command is pinned to one version of the original command: the version I tested against. "
        f"I recorded these versions on {d['recorded']} from the version line of each installed ado-file.",
        "",
        "Original commands change over time. A ctools command changes only when I update it to a newer version of "
        "the original and test against that version. I then update this page, the help file, and the ado-file "
        "header.",
        "",
    ]
    stale = behind(d, "#{command}")
    if stale:
        out += [behind_lead(stale), ""] + ["- " + markdown(item) for item in stale] + [""]
    out += [
        "Known differences between a ctools command and its pinned original are listed in "
        "[COMPATIBILITY.md](COMPATIBILITY.md) and in the command's help file.",
        "",
        "## Feedback and citation",
        "",
        f"Please report bugs and questions about ctools commands on the [issue tracker]({d['issues']}). The authors "
        "of the original commands do not maintain ctools. Undocumented differences between a ctools command and its "
        "original are bugs in ctools.",
        "",
        "If you use a ctools command in published work, please cite the original command. References are listed "
        "under each command below.",
        "",
        "## Community-contributed commands",
        "",
    ]
    body = []
    for c in d["commands"]:
        for o in community(c):
            body.append([
                f"[`{c['command']}`](#{c['command']})", f"`{o['name']}`", o["authors"], o["version"], o["date"],
                f"[{o['channel']}]({o['url']}), {o['distributed']}", markdown(o.get("status_short") or "Yes"),
            ])
    out += table_md(["ctools command", "Original", "Authors", "Pinned version", "Date", "Source", "Latest?"], body)
    out += [
        "",
        f"The Source column gives the distribution date of each package. I checked for newer versions on "
        f"{d['recorded']}.",
        "",
        "## Official Stata commands",
        "",
        f"These commands are pinned to official Stata commands as shipped with {stata['full']}. Official commands "
        "implemented as ado-files have a version line. Built-in commands do not.",
        "",
    ]
    body = []
    for c in d["commands"]:
        for o in official(c):
            link = f"[`{c['command']}`](#{c['command']})"
            if family(o):
                body.append([link, f"other `{o['which']}` commands", o["version"], "", ""])
            elif o["kind"] == "builtin":
                body.append([link, f"`{o['name']}`", "Built in", "", ""])
            else:
                manual = written_by(o)
                body.append([
                    link, f"`{o['name']}`", f"`{o['file']}` {o['version']}", o["date"],
                    manual[:1].upper() + manual[1:],
                ])
    out += table_md(["ctools command", "Original", "Pinned version", "Date", "Credit in the Stata manual"], body)
    out += ["", "## Details by command", ""]
    for c in d["commands"]:
        out += [f"### `{c['command']}`", "", markdown(c["intro"]), ""]
        for o in c["originals"]:
            out += table_md(["", ""], [[f"**{label}**", markdown(text)] for label, text in rows(d, o, checksum=True)])
            out += [""]
        for text in c.get("later", []) + c.get("credits", []):
            out += [markdown(text), ""]
        if supporting(d, c):
            out += [markdown(supporting(d, c)), ""]
        if c.get("references"):
            out += ["References:", ""] + ["- " + markdown(ref) for ref in c["references"]] + [""]
    out += [
        "## Supporting packages",
        "",
        "The original commands require these packages, or I used them as references in testing.",
        "",
    ]
    out += table_md(
        ["Package", "Authors", "Version", "Date", "Source", "Role", "SHA-256 of the ado-file"],
        [[f"`{s['name']}`", s["authors"], s["version"], s["date"], f"[{s['channel']}]({s['url']}), {s['distributed']}",
          markdown(s["role"]), f"`{s['sha256']}`"] for s in d["supporting"]],
    )
    out += ["", "## Other acknowledgments", "", "I also thank:", ""]
    out += ["- " + markdown(text) for text in d["algorithms"]]
    out += [
        "",
        "## Checking versions",
        "",
        "`which` shows the version line of an installed command, and `about` shows the Stata release:",
        "",
        "```stata",
        "which distinct",
        "which cdistinct",
        "ctools, version",
        "about",
        "```",
        "",
        "Checksums on this page are SHA-256 hashes of each ado-file with LF line endings:",
        "",
        "```sh",
        "tr -d '\\r' < distinct.ado | sha256sum",
        "```",
        "",
        "## Updating this page",
        "",
        "`config/attribution.json` records the pinned versions. `python scripts/sync_attribution.py` copies them to "
        "this page, the help files, and the ado-file headers. Run it with `--check` to find stale copies.",
        "",
    ]
    return "\n".join(out)


# ---------------------------------------------------------------- driver

def read(path):
    raw = path.read_bytes()
    return raw.decode("utf-8").replace("\r\n", "\n"), "\r\n" if b"\r\n" in raw else "\n"


def generated():
    d = json.loads((ROOT / "config/attribution.json").read_text(encoding="utf-8"))
    public = {p.stem for p in (ROOT / "build").glob("*.sthlp")} - {"ctools", "ctools_licenses"}
    named = {c["command"] for c in d["commands"]}
    if public != named:
        raise SystemExit(
            "config/attribution.json does not match the commands in build/: "
            f"missing {sorted(public - named)}, unknown {sorted(named - public)}"
        )
    known = {s["name"] for s in d["supporting"]}
    for c in d["commands"]:
        unknown = set(c.get("supporting", [])) - known
        if unknown:
            raise SystemExit(f"config/attribution.json: {c['command']} names unknown packages {sorted(unknown)}")
    files = {"docs/ATTRIBUTION.md": document(d)}
    for c in d["commands"]:
        name = c["command"]
        text = place_help(read(ROOT / f"build/{name}.sthlp")[0], help_block(d, c), name)
        files[f"build/{name}.sthlp"] = place_credit(text, credit_block(c), name)
        files[f"build/{name}.ado"] = place_ado(read(ROOT / f"build/{name}.ado")[0], ado_lines(c))
    files["build/ctools.sthlp"] = place_help(read(ROOT / "build/ctools.sthlp")[0], ctools_block(d), "ctools")
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, content in generated().items():
        path = ROOT / name
        current, eol = read(path) if path.exists() else (None, "\n")
        if current != content:
            if args.check:
                stale.append(name)
            else:
                path.write_bytes(content.replace("\n", eol).encode("utf-8"))
    if stale:
        raise SystemExit("Stale attribution: " + ", ".join(stale))
    print("Attribution checked" if args.check else "Attribution synchronized")


if __name__ == "__main__":
    main()
