"""Generate release identity from config/release.json; --check rejects stale copies."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generated():
    release = json.loads((ROOT / "config/release.json").read_text())
    v, date, minimum = (release[k] for k in ("version", "date", "stata_minimum"))
    # The ado/plugin protocol: change it whenever an ado-to-plugin argument or
    # result format changes, so _ctools_load refuses a mismatched pair.
    protocol = release["protocol"]
    if type(protocol) is not int or protocol < 1:
        raise SystemExit("config/release.json: protocol must be a positive integer")
    files = {}
    files["src/ctools_version.h"] = f'''/* Generated by scripts/sync_release.py from config/release.json. */
#ifndef CTOOLS_VERSION_H
#define CTOOLS_VERSION_H
#define CTOOLS_VERSION "{v}"
#define CTOOLS_RELEASE_DATE "{date}"
#define CTOOLS_PROTOCOL "{protocol}"
#ifndef CTOOLS_BUILD_REVISION
#define CTOOLS_BUILD_REVISION "local"
#endif
#endif
'''
    # Every package ado/help file carries the release stamp; files without one get it inserted.
    ado_stamp = f"*! version {v} {date} github.com/mdroste/stata-ctools"
    help_stamp = f"{{* *! version {v} {date}}}{{...}}"
    package_files = [
        "README.md",
        *sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "build").glob("*.ado")),
        *sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "build").glob("*.sthlp")),
        "build/ctools.pkg",
        "build/stata.toc",
    ]
    for filename in package_files:
        text = (ROOT / filename).read_text()
        if filename == "README.md":
            text = re.sub(r"!\[Version\]\([^\n]+\)", f"![Version](https://img.shields.io/badge/version-{v}-blue)", text)
        elif filename.endswith(".ado"):
            if re.match(r"\*! version ", text):
                text = re.sub(r"^\*! version .*", ado_stamp, text)
            else:
                text = ado_stamp + "\n" + text
            text = re.sub(r"\{col 56\}v[\d.]+", f"{{col 56}}v{v}", text)
            text = re.sub(r'local __ado_version "[\d.]+"', f'local __ado_version "{v}"', text)
            text = re.sub(r'local __ado_protocol "\d+"', f'local __ado_protocol "{protocol}"', text)
        elif filename.endswith(".sthlp"):
            if re.search(r"(?m)^\{\* \*! version [^}]+\}\{\.\.\.\}$", text):
                text = re.sub(r"(?m)^\{\* \*! version [^}]+\}\{\.\.\.\}$", help_stamp, text, count=1)
            else:
                text = re.sub(r"\A(\{smcl\}\n)?", lambda m: (m.group(1) or "") + help_stamp + "\n", text, count=1)
        elif filename.endswith(".toc"):
            if not re.search(r"(?m)^d Version: ", text):
                text = re.sub(r"(?m)^(d Requires: )", r"d Version: \n\1", text, count=1)
            text = re.sub(r"(?m)^d Version: .*$", f"d Version: {v}", text)
            text = re.sub(r"(?m)^d Requires: .*$", f"d Requires: Stata {minimum} or later", text)
        else:
            text = re.sub(r"(?m)^d Version: .*$", f"d Version: {v}", text)
            text = re.sub(r"(?m)^d Requires: .*$", f"d Requires: Stata {minimum} or later", text)
            text = re.sub(r"(?m)^d Distribution-Date: .*$", f"d Distribution-Date: {date}", text)
        files[filename] = text
    if files["build/_ctools_load.ado"].count(f'local __ado_protocol "{protocol}"') != 1:
        raise SystemExit("build/_ctools_load.ado must define __ado_protocol exactly once")
    for source in ("LICENSE", "docs/licenses/THIRD_PARTY_NOTICES"):
        files[f"build/{Path(source).name}"] = (ROOT / source).read_text()
    # net install leaves LICENSE and THIRD_PARTY_NOTICES behind as ancillary
    # files, so the same text is also installed as a help file. {asis} shows
    # the text verbatim; only {smcl} would end it.
    texts = [(ROOT / name).read_text() for name in ("LICENSE", "docs/licenses/THIRD_PARTY_NOTICES")]
    if any("{smcl}" in text for text in texts):
        raise SystemExit("License texts must not contain {smcl}")
    files["build/ctools_licenses.sthlp"] = (
        "{smcl}\n" + help_stamp + "\n"
        "{title:Title}\n\n"
        "{phang}\n{bf:ctools licenses} {hline 2} License of ctools and notices for the"
        " third-party code compiled into its plugins\n\n"
        "{pstd}\nThis is the text of the {cmd:LICENSE} and {cmd:THIRD_PARTY_NOTICES} files"
        " distributed with ctools. See {help ctools}.\n\n"
        "{title:ctools license}\n\n{asis}\n" + texts[0].rstrip("\n") + "\n{smcl}\n\n"
        "{title:Third-party notices}\n\n{asis}\n" + texts[1].rstrip("\n") + "\n{smcl}\n"
    )
    return files


def release_tag_error(tag):
    """Return why a release tag does not name config/release.json's version, or None."""
    version = json.loads((ROOT / "config/release.json").read_text())["version"]
    if tag != "v" + version:
        return f"Release tag {tag!r} does not match config/release.json version {version} (expected v{version})"
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--tag", help="fail unless this release tag is v<version>")
    args = parser.parse_args()
    if args.tag is not None and release_tag_error(args.tag):
        raise SystemExit(release_tag_error(args.tag))
    stale = []
    for name, content in generated().items():
        path = ROOT / name
        if not path.exists() or path.read_text() != content:
            if args.check: stale.append(name)
            else: path.write_text(content)
    if stale: raise SystemExit("Stale release metadata: " + ", ".join(stale))
    print("Release metadata checked" if args.check else "Release metadata synchronized")


if __name__ == "__main__":
    main()
