"""Inline the shared ado helpers of src/ado into the package's ado files.

Stata's net install takes at most 100 files per package (r(640) "package file
too long"), and a program defined in an ado file is visible only to the other
programs of that file. So instead of shipping each shared helper as its own
file, every package ado file carries, as its own subprograms, the src/ado
helpers it calls, directly or through another helper. They sit between
generated markers at the end of the file. A file's own subprogram is found
before any other program of that name, so a helper file left over from an
older install is never called.

Edit src/ado/<helper>.ado and run scripts/sync_release.py, which stamps the
release identity into the helpers and then regenerates these blocks;
scripts/sync_release.py --check rejects a stale block.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
HELPER_DIR = "src/ado"
BEGIN = ("* ctools-helpers:begin (generated by scripts/sync_release.py from src/ado; "
         "edit those files)")
END = "* ctools-helpers:end"
PROGRAM = re.compile(r"^[ \t]*program[ \t]+define[ \t]+(\w+)", re.M)


def strip_block(text):
    """The file without its generated helper block."""
    start = text.find("\n" + BEGIN)
    if start < 0:
        if BEGIN in text:
            raise SystemExit("ctools-helpers:begin must start a line")
        return text
    stop = text.find("\n" + END, start)
    if stop < 0:
        raise SystemExit("ctools-helpers:begin without ctools-helpers:end")
    if text[stop + len(END) + 1:].strip():
        raise SystemExit("text after the generated ctools-helpers block")
    return text[:start].rstrip("\n") + "\n"


def body(text):
    """A helper as inlined: without its release stamp, other *! lines as comments."""
    lines = text.rstrip("\n").split("\n")
    if lines and lines[0].startswith("*! version "):
        lines = lines[1:]
    lines = ["* " + line[2:].lstrip() if line.startswith("*!") else line for line in lines]
    while lines and not lines[0].strip():
        lines.pop(0)
    return "\n".join(lines)


def references(text, names):
    return {name for name in names if re.search(rf"(?<!\w){re.escape(name)}(?!\w)", text)}


def inline(host_name, host_text, helpers):
    """host_text with a freshly generated block of the helpers it needs.

    helpers maps helper name -> source text. A file that needs none is
    returned without a block (and otherwise unchanged)."""
    host = strip_block(host_text)
    if Path(host_name).stem in helpers:
        raise SystemExit(f"{host_name}: {Path(host_name).stem} is also a src/ado helper")
    needed, queue = set(), sorted(references(host, helpers))
    while queue:
        name = queue.pop()
        if name in needed:
            continue
        needed.add(name)
        queue.extend(sorted(references(helpers[name], helpers) - needed - {name}))
    if not needed:
        return host
    defined = {name: host_name for name in PROGRAM.findall(host)}
    blocks = []
    for name in sorted(needed):
        text = body(helpers[name])
        programs = PROGRAM.findall(text)
        if name not in programs:
            raise SystemExit(f"{HELPER_DIR}/{name}.ado does not define program {name}")
        for program in programs:
            if program in defined:
                raise SystemExit(f"{host_name}: program {program} of {name} is also "
                                 f"defined by {defined[program]}")
            defined[program] = name
        blocks.append(text)
    return (host.rstrip("\n") + "\n\n" + BEGIN + "\n" + "\n\n".join(blocks) + "\n" + END + "\n")


def inline_all(files):
    """Regenerate the helper block of every build/*.ado entry of files in place.

    Helper sources are taken from the src/ado/*.ado entries of files (as
    stamped by the caller), falling back to the files on disk."""
    helpers = {}
    for path in sorted((ROOT / HELPER_DIR).glob("*.ado")):
        key = f"{HELPER_DIR}/{path.name}"
        helpers[path.stem] = files.get(key, path.read_text())
    if not helpers:
        raise SystemExit(f"no helpers in {HELPER_DIR}")
    for key in sorted(files):
        if key.startswith("build/") and key.endswith(".ado"):
            files[key] = inline(key, files[key], helpers)
    return files
