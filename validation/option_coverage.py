"""Audit public option declarations against executable differential cases.

This is an inventory gate, not a claim that a passing call proves equivalence.
The runner separately checks all case/fixture results. Existing specialized
suites remain authoritative for format metadata, random draws, and diagnostics.
"""
from pathlib import Path
import argparse
import json
import re
from option_cases import CASES
ROOT=Path(__file__).resolve().parents[1]

def inventory(root=ROOT):
    found={}
    for path in sorted((root/'build').glob('c*.ado')):
        text=re.sub(r'/\*.*?\*/','',path.read_text(),flags=re.S)
        text=re.sub(r'///[^\n]*\n\s*',' ',text)
        program=None
        opts={}
        for line in text.splitlines():
            m=re.match(r'\s*program define (\w+)',line)
            if m: program=m[1]
            if program not in (path.stem,path.stem+'_excel','_'+path.stem+'_impl'): continue
            m=re.match(r'\s*(?:capture noisily |capture )?syntax\b(.*)',line)
            if not m or ',' not in m[1]: continue
            args=m[1].split(',',1)[1]
            # Remove balanced option argument declarations, preserving names.
            while '(' in args:
                new=re.sub(r'\([^()]*\)','',args)
                if new==args: raise ValueError('unbalanced syntax: '+str(path))
                args=new
            for token in re.findall(r'[A-Za-z_][A-Za-z_0-9:]*',args):
                token=token.replace(':','')
                if token=='options': continue
                opts[token.lower()]=token
        if path.stem=='cbsample': opts['weight']='weight'
        if not opts: raise ValueError("public command has no audited syntax: "+str(path))
        found[path.stem]=opts
    # Statistical-format dispatch options are composed in private adapters.
    for cmd,helper in [('cimport','_cio_import'),('cexport','_cio_export')]:
        for line in (root/f'build/{helper}.ado').read_text().splitlines():
            if 'local options' not in line: continue
            for token in re.findall(r'\b([A-Z][A-Za-z]*(?:\([^)]*\))?)',line):
                word=token.split('(')[0]
                if word!='CLEAR': found[cmd][word.lower()]=word
    shp=(root/'build/_cio_shp_export.ado').read_text()
    for line in shp.splitlines():
        if not re.match(r'\s*syntax\b',line): continue
        args=re.sub(r'\([^()]*\)','',line.split(',',1)[1])
        for token in re.findall(r'[A-Za-z_][A-Za-z_0-9]*',args):
            found['cexport'][token.lower()]=token
    return found

def exercised(case,option,declaration):
    if option not in case['options']: return False
    minimum=''.join(c for c in declaration if c.isupper()).lower() or option
    # Stata abbreviations must be prefixes, never substring mentions.
    tokens=re.findall(r'\b[a-zA-Z_][a-zA-Z_0-9]*\b',case['candidate'].lower())
    return any(option.startswith(t) and len(t)>=len(minimum) for t in tokens)

def records():
    legacy=json.loads((ROOT/'validation/option_evidence.json').read_text())
    rows=[]
    for cmd,options in inventory(ROOT).items():
        for option,declaration in options.items():
            cases=[i for i,c in enumerate(CASES) if c['command']==cmd and exercised(c,option,declaration)]
            if cmd.endswith('_p'):
                parent=cmd[:-2]
                cases=[i for i,c in enumerate(CASES) if c['command']==parent and option in c.get('predict','').split()]
            evidence=legacy.get(cmd,{}).get(option)
            if evidence:
                if evidence['kind'] not in ('differential','contract','rejection','unsupported') or not evidence['reason'] or not evidence['evidence']:
                    raise ValueError(f'invalid evidence: {cmd}.{option}')
                for e in evidence['evidence']:
                    path=ROOT/e['path']
                    if not path.exists() or e['anchor'] not in path.read_text():
                        raise ValueError(f'stale evidence: {cmd}.{option}: {e}')
            rows.append(dict(command=cmd,option=option,case_ids=cases,
                status='differential' if cases else evidence['kind'] if evidence else 'gap',
                evidence=evidence))
    extras={(cmd,opt) for cmd,opts in legacy.items() for opt in opts} - {(r['command'],r['option']) for r in rows}
    if extras: raise ValueError(f'stale option entries: {extras}')
    return rows

def report(rows):
    lines=['# Option coverage','',
      'Generated by `python3 validation/option_coverage.py --write`. This inventories parsed public options, including prediction and statistical-file adapters. It does not treat an option mention or a successful return code as a differential test.', '',
      'New differential cases run on three seeded input families and require seven significant digits, exact missing codes, identical variable/coefficient order, and matching estimation samples. Failed reference commands and incomplete runs fail the gate. Random sampling and unsupported/native-only interfaces require separate contracts.', '',
      'The inventory follows public syntax through transaction wrappers. Supplemental suites test option-specific saved estimates, diagnostic statistics, rendered graph/table properties, file bytes and sampling distributions. Accepted-but-ignored options must not pass solely because the main estimates are unchanged.', '',
      'The binscatter oracle exposes its original in-memory coordinate matrix in a namespaced test copy. It changes no calculations: mutation/identity tests compare native coefficients and CSV output byte for byte. This avoids interpreting short-format CSV rounding as a numerical implementation error.', '',
      'Run `python3 validation/option_coverage.py` and `python3 validation/test_option_inventory.py` for the inventory gates; run `python3 validation/test_option_coverage.py` for the new differential matrix. `python3 validation/run_stata_audit.py` includes this matrix, the option contracts, helper mutation tests and the existing suites. Stata runners use the configured interactive-login shell alias.', '',
      'This is finite option coverage, not an exhaustive Cartesian product of options or a proof for every possible dataset. A mapped option can still fail parity. Unsupported options are listed as rejection contracts rather than claimed equivalent implementations.', '',
      '| Command | Option | Evidence |','|---|---|---|']
    for r in rows:
        if r['case_ids']:
            status='New differential cases '+', '.join(map(str,r['case_ids']))
            if r['evidence']:
                status+='; '+r['evidence']['reason']+' '+', '.join('['+x['path'].split('/')[-1]+'](../'+x['path']+')' for x in r['evidence']['evidence'])
        elif r['evidence']:
            e=r['evidence'];status=e['kind']+': '+e['reason']+' '+', '.join('['+x['path'].split('/')[-1]+'](../'+x['path']+')' for x in e['evidence'])
        else: status='**GAP — no audited comparison**'
        lines.append(f'| `{r["command"]}` | `{r["option"]}` | {status} |')
    return '\n'.join(lines)+'\n'

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--write',action='store_true');p.add_argument('--allow-gaps',action='store_true');a=p.parse_args()
    rows=records();expected=report(rows);dest=ROOT/'docs/OPTION_COVERAGE.md'
    if a.write: dest.write_text(expected)
    elif not dest.exists() or dest.read_text()!=expected: raise SystemExit('stale docs/OPTION_COVERAGE.md')
    missing=[r for r in rows if r['status']=='gap']
    for r in missing: print('GAP',r['command'],r['option'])
    print(f'{len(rows)} options inventoried; {len(missing)} coverage gaps; {len(CASES)} cases x 3 fixtures')
    if missing and not a.allow_gaps: raise SystemExit(1)
if __name__=='__main__': main()
