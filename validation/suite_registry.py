from pathlib import Path
import argparse
import json
import os
import platform
import subprocess
import sys
from validation.support.stata_runner import ROOT, run_do

REGISTRY = ROOT / 'validation/suites.json'
MASTER = ROOT / 'validation/suites_master.do'


def load_registry():
    return json.loads(REGISTRY.read_text())['suites']


def master_names():
    return [s['name'] for s in load_registry() if s['runner'] == 'master']


def master_source():
    suites = [s for s in load_registry() if s['runner'] == 'master']
    return ('* Generated by suite_registry.py --write-master; edit suites.json.\n'
            'local scripts "' + ' '.join(s['name'] for s in suites) + '"\n'
            'local script_paths "' + ' '.join(s['path'] for s in suites) + '"\n')


def discovered_paths():
    # Support files with suite-like names remain registered as explicit helpers.
    # Fixtures, native C/support files and manual probes are not test drivers.
    directories = ('', 'stata', 'native/tests', 'checks', 'performance', 'support')
    patterns = ('validate_*.do', 'test_*.do', 'test_*.py', 'benchmark_*.do', 'benchmark_*.py')
    return {p.relative_to(ROOT).as_posix()
            for directory in directories
            for pattern in patterns
            for p in (ROOT / 'validation' / directory).glob(pattern)}


def check_registry():
    suites = load_registry()
    paths = [s['path'] for s in suites]
    if len(paths) != len(set(paths)):
        raise ValueError('duplicate suite paths')
    discovered = discovered_paths()
    if set(paths) != discovered:
        raise ValueError(f'registry mismatch: missing={discovered-set(paths)}, stale={set(paths)-discovered}')
    for s in suites:
        if s['runner'] not in ('master', 'native', 'do', 'python', 'helper', 'manual'):
            raise ValueError(f"unknown runner: {s['runner']}")
        if s['category'] not in ('correctness', 'large', 'performance', 'helper'):
            raise ValueError(f"unknown category: {s['category']}")
        if s['runner'] == 'python' and (not s.get('command') or not s.get('log')):
            raise ValueError(f"Python suite needs command and log: {s['name']}")
        for key in ('name', 'runner', 'category', 'fixtures', 'dependencies', 'marker'):
            if key not in s:
                raise ValueError(f'{s["path"]}: missing {key}')
        if s['runner'] in ('helper', 'manual') and not s.get('reason'):
            raise ValueError(f'{s["path"]}: exclusion needs a reason')
        if s['runner'] == 'master':
            assignment = 'global CTOOLS_COMPONENT_COMPLETE \"' + s['marker'] + '\"'
            if assignment not in (ROOT/s['path']).read_text():
                raise ValueError(f"missing completion assignment: {s['path']}")
        if s['runner'] in ('master', 'do', 'python') and not s['marker']:
            raise ValueError(f'{s["path"]}: missing completion marker')
    if not MASTER.exists() or MASTER.read_text() != master_source():
        raise ValueError('stale Stata registry; run suite_registry.py --write-master')


def transport_fixture():
    out = ROOT / 'temp/registry_transport'
    # This prepares a real SPI test plugin; it does not execute the benchmark.
    subprocess.run([sys.executable, '-m', 'validation.performance.benchmark_transport',
                    '--variant', f'current={ROOT / "src"}', '--output', str(out),
                    '--rows', '1', '--columns', '1', '--repetitions', '1'], cwd=ROOT, check=True)
    return out / 'current.plugin'


def run_extra_stata():
    check_registry()
    logs = ROOT / 'temp/registry_logs'
    logs.mkdir(parents=True, exist_ok=True)
    failures = []
    for suite in load_registry():
        if suite['category'] != 'correctness' or suite['runner'] not in ('python', 'do'):
            continue
        print('Running ' + suite['name'], flush=True)
        try:
            if suite['runner'] == 'python':
                subprocess.run([sys.executable, *suite['command'][1:]], cwd=ROOT, check=True)
                text = (ROOT/suite['log']).read_text(errors='replace')
                if suite['marker'] not in text.splitlines():
                    raise ValueError('missing registry completion marker: ' + suite['marker'])
            else:
                args = [transport_fixture()] if 'transport-plugin' in suite['fixtures'] else []
                run_do(ROOT/suite['path'], logs/(suite['name']+'.log'), args, [suite['marker']])
        except (subprocess.CalledProcessError, ValueError) as error:
            failures.append(suite['name'])
            print(f"FAIL {suite['name']}: {error}", flush=True)
    if failures:
        raise ValueError('Failed Stata suites: ' + ', '.join(failures))



def run_native():
    check_registry()
    failures = []
    for suite in load_registry():
        if suite['runner'] != 'native':
            continue
        env = os.environ.copy()
        # ASan policy matches the Linux gate; macOS suites choose their supported
        # defaults unless the caller explicitly asks for a sanitizer override.
        if platform.system() == 'Linux':
            for key, value in suite.get('env', {}).items(): env.setdefault(key, value)
        print('Running ' + suite['name'], flush=True)
        try:
            module = suite['path'][:-3].replace('/', '.')
            subprocess.run([sys.executable, '-m', module], cwd=ROOT, env=env, check=True)
        except subprocess.CalledProcessError:
            failures.append(suite['name'])
            print('FAIL ' + suite['name'], flush=True)
    if failures:
        raise ValueError('Failed native suites: ' + ', '.join(failures))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-master', action='store_true')
    parser.add_argument('--native', action='store_true')
    parser.add_argument('--extra-stata', action='store_true')
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()
    if args.write_master: MASTER.write_text(master_source())
    check_registry()
    if args.list:
        for s in load_registry(): print(s['category'], s['runner'], s['path'], s.get('reason', ''))
    if args.native: run_native()
    if args.extra_stata: run_extra_stata()
    print('Validation registry checked')


if __name__ == '__main__': main()
